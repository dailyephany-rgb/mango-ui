#!/usr/bin/env node
/**
 * Pull Web SDK config for mango-engineering into engFirebase.options.js
 * Creates a WEB app if the project has none.
 *
 * Usage:
 *   npm run eng:login
 *   npm run eng:pull-config
 */

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const PROJECT = process.env.ENG_FIREBASE_PROJECT || "mango-engineering";
const OUT = path.join(ROOT, "src/engineering/engFirebase.options.js");

function fail(msg) {
  console.error(`\n❌ ${msg}\n`);
  process.exit(1);
}

function ok(msg) {
  console.log(`✓ ${msg}`);
}

function firebase(args, opts = {}) {
  return spawnSync("npx", ["firebase-tools", "--project", PROJECT, ...args], {
    cwd: ROOT,
    encoding: "utf8",
    shell: false,
    ...opts,
  });
}

function parseJsonBlob(text) {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start < 0 || end <= start) return null;
  try {
    return JSON.parse(text.slice(start, end + 1));
  } catch {
    return null;
  }
}

function listWebApps() {
  const list = firebase(["apps:list", "WEB", "--json"]);
  const parsed = parseJsonBlob(`${list.stdout || ""}\n${list.stderr || ""}`);
  const apps = parsed?.result || [];
  return Array.isArray(apps) ? apps : [];
}

function ensureWebApp() {
  let apps = listWebApps();
  if (apps.length) return apps[0];

  console.log("No WEB app found — creating mango-eng-ui…");
  const created = firebase(["apps:create", "WEB", "mango-eng-ui", "--json"]);
  const parsed = parseJsonBlob(`${created.stdout || ""}\n${created.stderr || ""}`);
  if (parsed?.status === "success" && parsed?.result?.appId) {
    ok(`Created WEB app ${parsed.result.appId}`);
    return parsed.result;
  }
  // Re-list in case create succeeded but JSON mixed with warnings
  apps = listWebApps();
  if (apps.length) return apps[0];
  fail(
    `Could not create/list WEB app.\n${created.stdout || ""}\n${created.stderr || ""}`
  );
}

function pullSdkConfig(appId) {
  const sdk = firebase(["apps:sdkconfig", "WEB", appId, "--json"]);
  const combined = `${sdk.stdout || ""}\n${sdk.stderr || ""}`;
  const parsed = parseJsonBlob(combined);
  if (parsed?.status === "success" && parsed?.result) {
    const r = parsed.result;
    if (r.sdkConfig?.apiKey) return r.sdkConfig;
    if (r.fileContents) {
      try {
        return JSON.parse(r.fileContents);
      } catch {
        /* fall through */
      }
    }
    if (r.apiKey) return r;
  }
  if (parsed?.apiKey && parsed?.projectId) return parsed;
  if (parsed?.sdkConfig?.apiKey) return parsed.sdkConfig;
  // Non-json pretty output fallback
  const sdk2 = firebase(["apps:sdkconfig", "WEB", appId]);
  const pretty = parseJsonBlob(sdk2.stdout || "");
  if (pretty?.apiKey && pretty?.projectId) return pretty;
  if (pretty?.sdkConfig?.apiKey) return pretty.sdkConfig;
  fail(
    `sdkconfig failed for ${appId}.\n${combined}\n${sdk2.stdout || ""}\n${sdk2.stderr || ""}`
  );
}

function main() {
  if (PROJECT === "vasundhara-4c6e5") {
    fail("Refusing to pull clinical project as eng config");
  }

  console.log(`\nPull eng web config ← ${PROJECT}\n`);

  const app = ensureWebApp();
  const appId = app.appId || app.app_id;
  if (!appId) fail("WEB app missing appId");

  const cfg = pullSdkConfig(appId);
  if (!cfg?.apiKey || !cfg?.projectId) {
    fail(`Incomplete sdk config: ${JSON.stringify(cfg)}`);
  }
  if (cfg.projectId === "vasundhara-4c6e5") {
    fail("sdkconfig returned clinical project — abort");
  }

  const file = `/**
 * Engineering Firebase — DEDICATED project \`${cfg.projectId}\`.
 * Auto-generated by scripts/eng-pull-config.mjs — do not point at clinical.
 *
 * @type {import('firebase/app').FirebaseOptions | null}
 */
export const engFirebaseOptions = {
  apiKey: ${JSON.stringify(cfg.apiKey)},
  authDomain: ${JSON.stringify(cfg.authDomain || `${cfg.projectId}.firebaseapp.com`)},
  projectId: ${JSON.stringify(cfg.projectId)},
  storageBucket: ${JSON.stringify(cfg.storageBucket || `${cfg.projectId}.appspot.com`)},
  messagingSenderId: ${JSON.stringify(String(cfg.messagingSenderId || cfg.projectNumber || ""))},
  appId: ${JSON.stringify(cfg.appId || appId)},
};
`;
  fs.writeFileSync(OUT, file);
  ok(`Wrote ${path.relative(ROOT, OUT)}`);

  console.log(`
Optional .env.local overrides:
VITE_ENG_API_KEY=${cfg.apiKey}
VITE_ENG_AUTH_DOMAIN=${cfg.authDomain || `${cfg.projectId}.firebaseapp.com`}
VITE_ENG_PROJECT_ID=${cfg.projectId}
VITE_ENG_STORAGE_BUCKET=${cfg.storageBucket || `${cfg.projectId}.appspot.com`}
VITE_ENG_MESSAGING_SENDER_ID=${cfg.messagingSenderId || cfg.projectNumber || ""}
VITE_ENG_APP_ID=${cfg.appId || appId}
`);
}

main();
